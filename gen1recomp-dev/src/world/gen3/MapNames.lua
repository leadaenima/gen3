-- RUBY'S OWN MAP NAMES, keyed the way Game3 keys a map.
--
-- Generated from pokeruby's data/maps/map_groups.json: the group order and
-- each group's list give the same MAP_GROUP / MAP_NUM pair the cartridge
-- uses, and Game3.mapId spells that "g<group>_<num>".
--
-- WHY THE ENGINE CARRIES THESE AT ALL. A renderer mod keys its per-map shape
-- data by the map's DIRECTORY NAME -- "MauvilleCity", "Route110" -- because
-- that is the cartridge's own stable identity and the only thing a human can
-- author against. Our ids are ordinals, which name nothing.
--
-- AND WHY NOT BORROW EMERALD'S. The mod ships a table generated from
-- pokeemerald keyed by MAP_G<group>_N<num>, and it is tempting to just spell
-- our ids that way. 317 of Ruby's 394 maps land on the same-named Emerald
-- entry -- and 76 do NOT: Ruby has Contest Halls where Emerald has Battle
-- Tents, and its four Underwater maps are numbered differently. Keying by
-- index would hand those maps another map's tilesets, which is worse than
-- handing them nothing. Stating Ruby's own names means a lookup HITS where
-- the two games genuinely agree and MISSES where they do not, which is the
-- failure mode worth having.

